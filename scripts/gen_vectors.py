#!/usr/bin/env python3
"""Generate the stimulus and expected-response vectors the testbenches read.

The expected values come from focmodel, which is bit accurate against the RTL by
construction: same word lengths, same rounding points, same saturation.  The
testbenches therefore compare for equality and not against a tolerance.  A
tolerance would hide exactly the class of defect these vectors exist to catch,
an off-by-one in a shift or a rounding term.

The only place a tolerance appears anywhere in this repository is where the RTL
is compared against real arithmetic rather than against the model, and there the
bound is derived in docs/03-cordic.md before it is measured.

File format: '#' starts a comment line, data lines are whitespace-separated
decimal integers.  Stateful blocks take their configuration on the first data
line so that the testbench does not have to duplicate it.
"""

from __future__ import annotations

import argparse
import math
import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from focmodel import params as P
from focmodel.cordic import ROTATE, VECTOR, cordic
from focmodel.fixed import to_q, wrap
from focmodel.foc import CurrentLoop, PiAxis, clarke, svm

FULL = 1 << (P.W_ANG - 1)
ONE = 1 << P.Q_DATA


def _open(path: pathlib.Path, title: str, columns: str):
    f = path.open("w", encoding="utf-8", newline="\n")
    f.write(f"# {title}\n")
    f.write("# Generated by scripts/gen_vectors.py, do not edit.\n")
    f.write(f"# Columns: {columns}\n")
    return f


def gen_cordic_rot(out: pathlib.Path, n: int, rng: random.Random) -> None:
    with _open(out, "Rotation-mode CORDIC",
               "x_in y_in ang_in | x_out y_out ang_out") as f:
        cases = [(0, 0, 0), (ONE, 0, 0), (ONE, 0, FULL // 2), (ONE, 0, -FULL // 2),
                 (ONE, 0, FULL - 1), (ONE, 0, -FULL), (0, ONE, FULL // 4),
                 (2 * ONE, -2 * ONE, FULL - 1), (-2 * ONE, 2 * ONE, -FULL)]
        for _ in range(n - len(cases)):
            cases.append((rng.randint(-2 * ONE, 2 * ONE),
                          rng.randint(-2 * ONE, 2 * ONE),
                          rng.randint(-FULL, FULL - 1)))
        for x, y, a in cases:
            xo, yo, ao, _s = cordic(ROTATE, x, y, a)
            f.write(f"{x} {y} {a} {xo} {yo} {ao}\n")


def gen_cordic_vec(out: pathlib.Path, n: int, rng: random.Random) -> None:
    with _open(out, "Vectoring-mode CORDIC", "x_in y_in | mag ang_out") as f:
        cases = [(0, 0), (ONE, 0), (-ONE, 0), (0, ONE), (0, -ONE),
                 (ONE, ONE), (-ONE, ONE), (-ONE, -ONE), (ONE, -ONE),
                 (2 * ONE, 2 * ONE), (-2 * ONE, -2 * ONE)]
        for _ in range(n - len(cases)):
            cases.append((rng.randint(-2 * ONE, 2 * ONE),
                          rng.randint(-2 * ONE, 2 * ONE)))
        for x, y in cases:
            xo, _yo, ao, _s = cordic(VECTOR, x, y, 0)
            f.write(f"{x} {y} {xo} {ao}\n")


def gen_clarke(out: pathlib.Path, n: int, rng: random.Random) -> None:
    with _open(out, "Clarke transform", "ia ib | ialpha ibeta sat") as f:
        cases = [(0, 0), (ONE, 0), (0, ONE), (ONE, -ONE), (-ONE, ONE)]
        # A full electrical turn of a balanced 1 pu set, the case the block
        # actually spends its life on.
        for k in range(360):
            th = k * math.pi / 180.0
            cases.append((to_q(math.cos(th), P.Q_DATA, P.W_DATA),
                          to_q(math.cos(th - 2.0 * math.pi / 3.0),
                               P.Q_DATA, P.W_DATA)))
        for _ in range(n - len(cases)):
            cases.append((rng.randint(-2 * ONE, 2 * ONE),
                          rng.randint(-2 * ONE, 2 * ONE)))
        for ia, ib in cases:
            al, be, st = clarke(ia, ib)
            f.write(f"{ia} {ib} {al} {be} {1 if st else 0}\n")


def gen_pi(out: pathlib.Path, rng: random.Random) -> None:
    with _open(out, "PI axis, stateful; first data line is kp ki umax",
               "ref meas | u sat") as f:
        f.write(f"{P.KP_Q} {P.KI_Q} {P.V_MAX_Q}\n")
        pi = PiAxis(P.KP_Q, P.KI_Q, P.V_MAX_Q)
        seq: list[tuple[int, int]] = []
        # Step into the limit and hold there long enough that a controller
        # without anti-windup would have wound up badly, then step back.  The
        # recovery transient is the whole point of the test.
        seq += [(to_q(0.5, P.Q_DATA, P.W_DATA), 0)] * 200
        seq += [(to_q(0.5, P.Q_DATA, P.W_DATA),
                 to_q(0.5, P.Q_DATA, P.W_DATA))] * 100
        seq += [(0, to_q(0.5, P.Q_DATA, P.W_DATA))] * 100
        seq += [(to_q(-0.5, P.Q_DATA, P.W_DATA), 0)] * 200
        seq += [(0, 0)] * 50
        for _ in range(200):
            seq.append((rng.randint(-ONE, ONE), rng.randint(-ONE, ONE)))
        for ref, meas in seq:
            u = pi.step(ref, meas)
            f.write(f"{ref} {meas} {u} {1 if pi.sat else 0}\n")


def gen_svm(out: pathlib.Path, n: int, rng: random.Random) -> None:
    with _open(out, "Modulator; first data line is pwm_top",
               "valpha vbeta | cmp_a cmp_b cmp_c over") as f:
        f.write(f"{P.PWM_TOP}\n")
        cases = [(0, 0)]
        # Balanced sets at the linear limit and beyond it, and a full turn at
        # half amplitude, which is where the duty symmetry is easiest to see.
        for amp in (0.5, 1.0, 1.1):
            for k in range(0, 360, 3):
                th = k * math.pi / 180.0
                va = amp * math.cos(th)
                vb = amp * math.cos(th - 2.0 * math.pi / 3.0)
                al = va
                be = (va + 2.0 * vb) / math.sqrt(3.0)
                cases.append((to_q(al, P.Q_DATA, P.W_DATA),
                              to_q(be, P.Q_DATA, P.W_DATA)))
        for _ in range(n - len(cases)):
            cases.append((rng.randint(-ONE, ONE), rng.randint(-ONE, ONE)))
        for al, be in cases:
            cmps, over = svm(al, be, P.PWM_TOP)
            f.write(f"{al} {be} {cmps[0]} {cmps[1]} {cmps[2]} "
                    f"{1 if over else 0}\n")


def gen_current_loop(out: pathlib.Path, n: int, rng: random.Random) -> None:
    with _open(out, "Current loop, stateful; first data line is kp ki vmax top",
               "ia ib theta id_ref iq_ref | id iq vd vq cmp_a cmp_b cmp_c") as f:
        f.write(f"{P.KP_Q} {P.KI_Q} {P.V_MAX_Q} {P.PWM_TOP}\n")
        loop = CurrentLoop(P.KP_Q, P.KI_Q, P.V_MAX_Q, P.PWM_TOP)
        rows: list[tuple[int, int, int, int, int]] = []
        # A machine turning at constant speed with the loop asked for 0.5 pu of
        # torque current: the trajectory the block is designed for.
        iq_ref = to_q(0.5, P.Q_DATA, P.W_DATA)
        for k in range(n // 2):
            th = (k * 137) % 65536 - 32768
            amp = 0.4
            ia = to_q(amp * math.cos(th / FULL * math.pi), P.Q_DATA, P.W_DATA)
            ib = to_q(amp * math.cos(th / FULL * math.pi - 2.0 * math.pi / 3.0),
                      P.Q_DATA, P.W_DATA)
            rows.append((ia, ib, th, 0, iq_ref))
        for _ in range(n - len(rows)):
            rows.append((rng.randint(-ONE, ONE), rng.randint(-ONE, ONE),
                         rng.randint(-FULL, FULL - 1),
                         rng.randint(-ONE // 4, ONE // 4),
                         rng.randint(-ONE, ONE)))
        for ia, ib, th, idr, iqr in rows:
            r = loop.step(ia, ib, wrap(th, P.W_ANG), idr, iqr)
            f.write(f"{ia} {ib} {th} {idr} {iqr} "
                    f"{r['id']} {r['iq']} {r['vd']} {r['vq']} "
                    f"{r['cmp'][0]} {r['cmp'][1]} {r['cmp'][2]}\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="sim/vectors")
    ap.add_argument("--seed", type=int, default=20260822)
    args = ap.parse_args()

    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(args.seed)

    gen_cordic_rot(out / "cordic_rot.txt", 2000, rng)
    gen_cordic_vec(out / "cordic_vec.txt", 2000, rng)
    gen_clarke(out / "clarke.txt", 600, rng)
    gen_pi(out / "pi_axis.txt", rng)
    gen_svm(out / "svm.txt", 600, rng)
    gen_current_loop(out / "current_loop.txt", 400, rng)

    for p in sorted(out.glob("*.txt")):
        rows = sum(1 for ln in p.read_text(encoding="utf-8").splitlines()
                   if ln and not ln.startswith("#"))
        print(f"{p}: {rows} data lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

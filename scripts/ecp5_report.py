#!/usr/bin/env python3
"""Turn the nextpnr report of scripts/ecp5_flow.sh into committed results.

    ecp5_report.py --write --build build/ecp5 ...   rewrite fpga/ecp5/results.*
    ecp5_report.py --check --build build/ecp5 ...   compare with the committed copy

Both modes exit non-zero if the achieved Fmax of the fabric clock is below the
constraint, so timing that is not met fails the flow whatever else happens.

The check mode compares resource counts exactly and Fmax within a small
tolerance.  The flow is pinned by container digest and seed and has been
deterministic in practice. A placer is entitled to land a fraction of a
per cent differently on a different host CPU and that is not a regression.

Every number written comes from the tools.  Nothing here is measured on
hardware and the files say so in their first lines.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEST = ROOT / "fpga" / "ecp5"
FMAX_TOLERANCE = 0.02

# The resources worth a row, in the order a reader looks for them.
RESOURCES = [
    ("TRELLIS_COMB", "Logic cells (LUT4 or carry half)"),
    ("TRELLIS_FF", "Flip-flops"),
    ("MULT18X18D", "18x18 multipliers"),
    ("ALU54B", "54-bit DSP ALUs"),
    ("DP16KD", "16 kbit block RAMs"),
    ("TRELLIS_RAMW", "Distributed RAM write ports"),
    ("TRELLIS_IO", "I/O pins"),
    ("DCCA", "Global clock buffers"),
]

LABEL = (
    "Tool estimates from open-source synthesis and place-and-route for one "
    "device. Not a vendor sign-off and not measured on hardware."
)


def first_line(path: pathlib.Path) -> str:
    text = path.read_text(encoding="utf-8", errors="replace").strip()
    return text.splitlines()[0].strip() if text else ""


def nextpnr_version(path: pathlib.Path) -> str:
    """nextpnr-ecp5 --version prints a banner; keep the version string in it."""
    line = first_line(path)
    m = re.search(r"Version\s+([^)\s]+)", line)
    return f"nextpnr-ecp5 {m.group(1)}" if m else line


def yosys_cells(stat: pathlib.Path) -> dict[str, int]:
    """Cell counts from the top-level section of Yosys's stat output."""
    cells: dict[str, int] = {}
    for line in stat.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\s+(\d+)\s+([A-Z][A-Z0-9_]+)\s*$", line)
        if m:
            cells[m.group(2)] = int(m.group(1))
    return dict(sorted(cells.items()))


def path_summary(cp: dict) -> dict:
    steps = cp["path"]
    total = sum(s["delay"] for s in steps)
    routing = sum(s["delay"] for s in steps if s["type"] == "routing")
    return {
        "from": steps[0]["from"]["cell"],
        "to": steps[-1]["to"]["cell"],
        "delay_ns": round(total, 3),
        "logic_ns": round(total - routing, 3),
        "routing_ns": round(routing, 3),
    }


def build_results(args: argparse.Namespace) -> dict:
    build = pathlib.Path(args.build)
    report = json.loads((build / "report.json").read_text(encoding="utf-8"))

    clocks = report["fmax"]
    if len(clocks) != 1:
        sys.exit(f"expected one clock domain, found {sorted(clocks)}")
    clk = next(iter(clocks.values()))

    reg_paths = [
        c for c in report["critical_paths"]
        if c["from"].startswith("posedge") and c["to"].startswith("posedge")
    ]

    util = {}
    for key, _ in RESOURCES:
        u = report["utilization"].get(key)
        if u is not None:
            util[key] = {"used": u["used"], "available": u["available"]}

    return {
        "label": LABEL,
        "target": {
            "device": args.device,
            "family": "Lattice ECP5",
            "clock_constraint_mhz": float(args.freq),
            "placer_seed": int(args.seed),
            "io_constraints": "none; I/O placed by the tool, I/O paths not constrained",
        },
        "tools": {
            "ghdl": first_line(build / "ghdl.version"),
            "yosys": first_line(build / "yosys.version"),
            "nextpnr": nextpnr_version(build / "nextpnr.version"),
            "synthesis_image": args.yosys_image,
            "place_and_route_image": args.nextpnr_image,
        },
        "timing": {
            "fmax_mhz": round(clk["achieved"], 2),
            "constraint_mhz": round(clk["constraint"], 2),
            "met": clk["achieved"] >= clk["constraint"],
            "critical_path": path_summary(reg_paths[0]) if reg_paths else None,
        },
        "utilisation": util,
        "synthesis_cells": yosys_cells(build / "yosys_stat.txt"),
    }


def render_md(r: dict) -> str:
    t = r["timing"]
    lines = [
        "<!-- GENERATED by scripts/ecp5_flow.sh, do not edit. -->",
        "",
        f"# ECP5 implementation results: {r['target']['device']}",
        "",
        f"> **{r['label']}**",
        "",
        "| | |",
        "| --- | --- |",
        f"| Device | {r['target']['device']} ({r['target']['family']}) |",
        f"| Clock constraint | {t['constraint_mhz']:.0f} MHz |",
        f"| Fmax, fabric clock, nextpnr estimate | {t['fmax_mhz']:.2f} MHz |",
        f"| Timing at the constraint | {'met' if t['met'] else 'NOT MET'} |",
        f"| Placer seed | {r['target']['placer_seed']} |",
        f"| I/O | {r['target']['io_constraints']} |",
        "",
        "## Utilisation after place and route",
        "",
        "| Resource | Used | Available | Per cent |",
        "| --- | ---: | ---: | ---: |",
    ]
    names = dict(RESOURCES)
    for key, u in r["utilisation"].items():
        pct = 100.0 * u["used"] / u["available"] if u["available"] else 0.0
        lines.append(f"| {names[key]} (`{key}`) | {u['used']} | {u['available']} "
                     f"| {pct:.1f} |")
    lines += [
        "",
        "## Cells after synthesis",
        "",
        "| Cell | Count |",
        "| --- | ---: |",
    ]
    for k, v in r["synthesis_cells"].items():
        lines.append(f"| `{k}` | {v} |")
    cp = t["critical_path"]
    if cp:
        lines += [
            "",
            "## Critical register-to-register path",
            "",
            f"`{cp['from']}` to `{cp['to']}`: {cp['delay_ns']:.2f} ns, of which "
            f"{cp['logic_ns']:.2f} ns logic and {cp['routing_ns']:.2f} ns routing.",
        ]
    lines += [
        "",
        "## Tools",
        "",
        f"- GHDL: {r['tools']['ghdl']}",
        f"- Yosys: {r['tools']['yosys']}",
        f"- nextpnr: {r['tools']['nextpnr']}",
        f"- Synthesis image: `{r['tools']['synthesis_image']}`",
        f"- Place and route image: `{r['tools']['place_and_route_image']}`",
        "",
    ]
    return "\n".join(lines)


def compare(old: dict, new: dict) -> list[str]:
    problems = []
    for key in ("target", "utilisation", "synthesis_cells"):
        if old.get(key) != new.get(key):
            problems.append(f"{key} differs:\n  committed {old.get(key)}\n  now       "
                            f"{new.get(key)}")
    for key in ("ghdl", "yosys", "nextpnr"):
        if old["tools"].get(key) != new["tools"].get(key):
            problems.append(f"tool version differs: {key}")
    f_old = old["timing"]["fmax_mhz"]
    f_new = new["timing"]["fmax_mhz"]
    if abs(f_new - f_old) > FMAX_TOLERANCE * f_old:
        problems.append(f"Fmax moved from {f_old} to {f_new} MHz")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--build", required=True)
    ap.add_argument("--device", required=True)
    ap.add_argument("--freq", required=True)
    ap.add_argument("--seed", required=True)
    ap.add_argument("--yosys-image", required=True)
    ap.add_argument("--nextpnr-image", required=True)
    args = ap.parse_args()

    r = build_results(args)
    t = r["timing"]
    cp = t["critical_path"]
    print(f"{r['target']['device']}: Fmax {t['fmax_mhz']:.2f} MHz against "
          f"{t['constraint_mhz']:.0f} MHz, {'met' if t['met'] else 'NOT MET'}")
    if cp:
        print(f"critical path {cp['from']} -> {cp['to']}: {cp['delay_ns']:.2f} ns")
    for key, u in r["utilisation"].items():
        print(f"  {key:14s} {u['used']:6d} / {u['available']}")

    rc = 0
    if args.write:
        DEST.mkdir(parents=True, exist_ok=True)
        with open(DEST / "results.json", "w", encoding="utf-8", newline="\n") as f:
            json.dump(r, f, indent=2)
            f.write("\n")
        with open(DEST / "results.md", "w", encoding="utf-8", newline="\n") as f:
            f.write(render_md(r))
        print(f"wrote {DEST.relative_to(ROOT).as_posix()}/results.json and results.md")
    else:
        committed = DEST / "results.json"
        if not committed.exists():
            print("fpga/ecp5/results.json is missing, run scripts/ecp5_flow.sh",
                  file=sys.stderr)
            rc = 1
        else:
            problems = compare(json.loads(committed.read_text(encoding="utf-8")), r)
            for p in problems:
                print(p, file=sys.stderr)
            if problems:
                print("committed results are stale, run scripts/ecp5_flow.sh and "
                      "commit fpga/ecp5/", file=sys.stderr)
                rc = 1
            else:
                print("committed results match")

    if not t["met"]:
        print(f"TIMING NOT MET: {t['fmax_mhz']:.2f} MHz against "
              f"{t['constraint_mhz']:.0f} MHz", file=sys.stderr)
        rc = 1
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
